plugins {
    `java-library`
    id("com.diffplug.spotless") version "8.0.0"
    id("com.github.spotbugs") version "6.4.4"
    id("net.ltgt.errorprone") version "5.2.0"
    checkstyle
    id("com.vanniktech.maven.publish") version "0.34.0"
}

description = "Reading, writing and converting PAGE XML documents in Java"

repositories {
    mavenCentral()
}

java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
    }
    withSourcesJar()
}

dependencies {
    api("org.jspecify:jspecify:1.0.0")
    compileOnly("io.soabase.record-builder:record-builder-core:53")
    annotationProcessor("io.soabase.record-builder:record-builder-processor:53")
    errorprone("com.google.errorprone:error_prone_core:2.52.0")
    errorprone("com.uber.nullaway:nullaway:0.14.3")
    testImplementation(platform("org.junit:junit-bom:5.10.2"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

tasks.withType<JavaCompile> {
    options.encoding = "UTF-8"
    // missing-explicit-ctor: implicit public constructors of exported classes are intended API.
    // processing, requires-automatic: RecordBuilder is an automatic module whose annotations are
    // only read at compile time.
    options.compilerArgs.addAll(
        listOf("-Xlint:all,-serial,-missing-explicit-ctor,-processing,-requires-automatic")
    )
}

tasks.withType<JavaCompile>().configureEach {
    options.errorprone {
        disableAllChecks.set(true)
        // Builders generated by RecordBuilder are not annotated for NullAway.
        excludedPaths.set(".*/build/generated/.*")
        check("NullAway", CheckSeverity.ERROR)
        option("NullAway:OnlyNullMarked", "true")
        option("NullAway:JSpecifyMode", "true")
    }
}

tasks.named<JavaCompile>("compileTestJava") {
    options.errorprone.enabled.set(false)
}

tasks.test {
    useJUnitPlatform()
}

tasks.withType<Jar> {
    from(files("LICENSE", "NOTICE")) {
        into("META-INF")
    }
}

tasks.withType<Javadoc> {
    options {
        (this as StandardJavadocDocletOptions).apply {
            addStringOption("Xdoclint:none", "-quiet")
            encoding = "UTF-8"
            charSet = "UTF-8"
            docEncoding = "UTF-8"
            links("https://docs.oracle.com/en/java/javase/25/docs/api/")
            windowTitle = "page4j ${project.version} API"
            docTitle = "page4j ${project.version}"
            header = "<b>page4j</b>"
            bottom = "Copyright &copy; 2026 Maximilian Nöth. Licensed under the Apache License 2.0."
        }
    }
}

// The builders are generated by the annotation processor and are part of the API.
tasks.javadoc {
    source(tasks.compileJava.flatMap { it.options.generatedSourceOutputDirectory })
}

spotless {
    java {
        googleJavaFormat("1.28.0")
