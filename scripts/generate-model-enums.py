#!/usr/bin/env python3
"""Generates the enumerations of com.maxnth.page4j.model.value from the bundled PAGE schemas.

Each enum holds the union of the values of all schema versions, in order of first appearance.
Run from the repository root after adding or changing a schema:

    python3 scripts/generate-model-enums.py

ModelEnumsMatchSchemasTest fails when the checked-in enums and the schemas disagree.
"""

import glob
import os
import re
import xml.etree.ElementTree as ET

XS = "{http://www.w3.org/2001/XMLSchema}"
SCHEMAS = "src/main/resources/com/maxnth/page4j/pagexml/schemas/*_pagecontent.xsd"
TARGET = "src/main/java/com/maxnth/page4j/model/value"

# Java enum name -> (description, source). A source is a named simple type, or
# "ComplexType@attribute" for an enumeration declared inline on an attribute.
ENUMS = {
    "Align": ("Text alignment of a text region.", "AlignSimpleType"),
    "ChartType": ("Type of a chart region.", "ChartTypeSimpleType"),
    "ColourDepth": ("Colour depth of an image region.", "ColourDepthSimpleType"),
    "Colour": ("A named colour.", "ColourSimpleType"),
    "GraphicsType": ("Type of a graphic region.", "GraphicsTypeSimpleType"),
    "GroupType": ("Type of a reading order group.", "GroupTypeSimpleType"),
    "Language": ("A language.", "LanguageSimpleType"),
    "Mirrored": ("Whether and how an object is mirrored.", "MirroredSimpleType"),
    "PageType": ("Type of a page.", "PageTypeSimpleType"),
    "Production": ("How the text of an object was produced.", "ProductionSimpleType"),
    "ReadingDirection": ("Reading direction of text.", "ReadingDirectionSimpleType"),
    "Script": ("A writing system.", "ScriptSimpleType"),
    "TextDataType": ("Data type of a text equivalent.", "TextDataTypeSimpleType"),
    "TextLineOrder": ("Order of the text lines of a region.", "TextLineOrderSimpleType"),
    "TextType": ("Type of a text region.", "TextTypeSimpleType"),
    "UnderlineStyle": ("Style of underlined text.", "UnderlineStyleSimpleType"),
    "CharType": ("Kind of a grapheme.", "GraphemeBaseType@charType"),
    "MetadataItemType": ("Type of a metadata item.", "MetadataItemType@type"),
    "ResolutionUnit": ("Unit of the image resolution of a page.", "PageType@imageResolutionUnit"),
    "RelationType": ("Type of a relation.", "RelationType@type"),
    "UserAttributeType": ("Data type of a user-defined attribute.", "UserAttributeType@type"),
}

HEADER = "// Generated by scripts/generate-model-enums.py from the bundled PAGE schemas. Do not edit.\n\n"


def enumerations(element):
    return [e.get("value") for e in element.iter(XS + "enumeration")]


def collect():
    """Returns {source: [values in order of first appearance across versions]}."""
    values = {}
    for path in sorted(glob.glob(SCHEMAS)):
        root = ET.parse(path).getroot()
        found = {}
        for simple in root.findall(XS + "simpleType"):
            found[simple.get("name")] = enumerations(simple)
        for complex_type in root.findall(XS + "complexType"):
            for attribute in complex_type.iter(XS + "attribute"):
                found[complex_type.get("name") + "@" + attribute.get("name")] = enumerations(attribute)
        for source, vals in found.items():
            union = values.setdefault(source, [])
            for value in vals:
                if value not in union:
                    union.append(value)
    return values


def constant_name(value):
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)  # camelCase -> camel_Case
    name = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()
    if name[0].isdigit():
        name = "_" + name
    return name


def java_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(name, description, values):
    constants = []
    seen = {}
    for value in values:
        constant = constant_name(value)
        if constant in seen:
            raise SystemExit(f"{name}: '{value}' and '{seen[constant]}' both map to {constant}")
        seen[constant] = value
        constants.append(f"  {constant}({java_string(value)})")
    body = ",\n".join(constants)
    return f"""{HEADER}package com.maxnth.page4j.model.value;

import java.util.HashMap;
import java.util.Map;

/**
 * {description}
 *
 * <p>Holds the values of all PAGE XML versions; a value may not exist in every version.
 */
public enum {name} implements XmlValue {{
{body};

  private static final Map<String, {name}> BY_XML_VALUE = new HashMap<>();

  static {{
    for ({name} value : values()) {{
      BY_XML_VALUE.put(value.xmlValue, value);
    }}
  }}

  private final String xmlValue;

  {name}(String xmlValue) {{
    this.xmlValue = xmlValue;
  }}

  @Override
  public String xmlValue() {{
    return xmlValue;
  }}

  /**
   * Returns the constant with the given XML value.
   *
   * @throws IllegalArgumentException if no PAGE XML version defines the value
   */
  public static {name} fromXml(String xmlValue) {{
    {name} value = BY_XML_VALUE.get(xmlValue);
    if (value == null) {{
      throw new IllegalArgumentException("Unknown {name} value: '" + xmlValue + "'");
    }}
    return value;
  }}
}}
"""


def main():
    values = collect()
    os.makedirs(TARGET, exist_ok=True)
    for name, (description, source) in ENUMS.items():
        if source not in values or not values[source]:
            raise SystemExit(f"No enumeration values for {source}")
        with open(os.path.join(TARGET, name + ".java"), "w", encoding="utf-8") as out:
            out.write(render(name, description, values[source]))
    print(f"Generated {len(ENUMS)} enums in {TARGET}")


if __name__ == "__main__":
    main()
