package com.maxnth.page4j.model.value;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Stream;
import javax.xml.parsers.DocumentBuilderFactory;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;

/** The enums are generated by {@code scripts/generate-model-enums.py}; rerun it if this fails. */
class ModelEnumsMatchSchemasTest {

  private static final String XS = "http://www.w3.org/2001/XMLSchema";
  private static final String SCHEMAS = "/com/maxnth/page4j/pagexml/schemas/";
  private static final List<String> VERSIONS =
      List.of(
          "2009-03-16",
          "2010-01-12",
          "2010-03-19",
          "2013-07-15",
          "2016-07-15",
          "2017-07-15",
          "2018-07-15",
          "2019-07-15",
          "2024-07-15");

  /** Enum -> named simple type, or "ComplexType@attribute" for an inline enumeration. */
  private static final Map<Class<? extends Enum<?>>, String> SOURCES = new LinkedHashMap<>();

  static {
    SOURCES.put(Align.class, "AlignSimpleType");
    SOURCES.put(ChartType.class, "ChartTypeSimpleType");
    SOURCES.put(ColourDepth.class, "ColourDepthSimpleType");
    SOURCES.put(Colour.class, "ColourSimpleType");
    SOURCES.put(GraphicsType.class, "GraphicsTypeSimpleType");
    SOURCES.put(GroupType.class, "GroupTypeSimpleType");
    SOURCES.put(Language.class, "LanguageSimpleType");
    SOURCES.put(Mirrored.class, "MirroredSimpleType");
    SOURCES.put(PageType.class, "PageTypeSimpleType");
    SOURCES.put(Production.class, "ProductionSimpleType");
    SOURCES.put(ReadingDirection.class, "ReadingDirectionSimpleType");
    SOURCES.put(Script.class, "ScriptSimpleType");
    SOURCES.put(TextDataType.class, "TextDataTypeSimpleType");
    SOURCES.put(TextLineOrder.class, "TextLineOrderSimpleType");
    SOURCES.put(TextType.class, "TextTypeSimpleType");
    SOURCES.put(UnderlineStyle.class, "UnderlineStyleSimpleType");
    SOURCES.put(CharType.class, "GraphemeBaseType@charType");
    SOURCES.put(MetadataItemType.class, "MetadataItemType@type");
    SOURCES.put(ResolutionUnit.class, "PageType@imageResolutionUnit");
    SOURCES.put(RelationType.class, "RelationType@type");
    SOURCES.put(UserAttributeType.class, "UserAttributeType@type");
  }

  private static final Map<String, List<String>> SCHEMA_VALUES = collect();

  static Stream<Arguments> enums() {
    return SOURCES.entrySet().stream().map(e -> Arguments.of(e.getKey(), e.getValue()));
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("enums")
  void enumHoldsTheUnionOfAllSchemaVersions(Class<? extends Enum<?>> type, String source) {
    List<String> expected = SCHEMA_VALUES.getOrDefault(source, List.of());
    List<String> actual =
        Arrays.stream(type.getEnumConstants()).map(c -> ((XmlValue) c).xmlValue()).toList();
    assertEquals(expected, actual, type.getSimpleName() + " vs " + source);
  }

  @Test
  void everyEnumOfTheSchemasHasAJavaEnum() {
    Set<String> unmapped = new LinkedHashSet<>(SCHEMA_VALUES.keySet());
    unmapped.removeAll(SOURCES.values());
    assertEquals(Set.of(), unmapped);
  }

  @Test
  void fromXmlLooksUpByXmlValue() {
    assertSame(UnderlineStyle.SINGLE_LINE, UnderlineStyle.fromXml("singleLine"));
    assertSame(UserAttributeType.XSD_STRING, UserAttributeType.fromXml("xsd:string"));
    assertThrows(IllegalArgumentException.class, () -> TextType.fromXml("no-such-type"));
  }

  private static Map<String, List<String>> collect() {
    Map<String, List<String>> values = new LinkedHashMap<>();
    for (String version : VERSIONS) {
      Document schema = parse(version);
      for (Element type : children(schema.getDocumentElement(), "simpleType")) {
        add(values, type.getAttribute("name"), enumerations(type));
      }
      for (Element type : children(schema.getDocumentElement(), "complexType")) {
        NodeList attributes = type.getElementsByTagNameNS(XS, "attribute");
        for (int i = 0; i < attributes.getLength(); i++) {
          Element attribute = (Element) attributes.item(i);
          String key = type.getAttribute("name") + "@" + attribute.getAttribute("name");
          add(values, key, enumerations(attribute));
        }
      }
    }
    values.values().removeIf(List::isEmpty);
    return values;
  }

  private static void add(Map<String, List<String>> values, String key, List<String> found) {
    List<String> union = values.computeIfAbsent(key, k -> new ArrayList<>());
    for (String value : found) {
      if (!union.contains(value)) {
        union.add(value);
      }
    }
  }

  private static List<String> enumerations(Element element) {
    NodeList nodes = element.getElementsByTagNameNS(XS, "enumeration");
    List<String> result = new ArrayList<>();
    for (int i = 0; i < nodes.getLength(); i++) {
      result.add(((Element) nodes.item(i)).getAttribute("value"));
    }
    return result;
  }

  private static List<Element> children(Element parent, String localName) {
    List<Element> result = new ArrayList<>();
    for (var node = parent.getFirstChild(); node != null; node = node.getNextSibling()) {
      if (node instanceof Element e
          && XS.equals(e.getNamespaceURI())
          && localName.equals(e.getLocalName())) {
        result.add(e);
      }
    }
    return result;
  }

  private static Document parse(String version) {
    String resource = SCHEMAS + version + "_pagecontent.xsd";
    try (InputStream in = ModelEnumsMatchSchemasTest.class.getResourceAsStream(resource)) {
      if (in == null) {
        throw new IllegalStateException("Missing " + resource);
      }
      var factory = DocumentBuilderFactory.newInstance();
      factory.setNamespaceAware(true);
      return factory.newDocumentBuilder().parse(in);
    } catch (Exception e) {
      throw new IllegalStateException("Cannot parse " + resource, e);
    }
  }
}
